# ─── Context ─────────────────────────────────────────────────────────────────

@dataclass
class ToolContext:
    """Per-request context handed to every handler."""
    db: Optional[Session]
    user: Any  # Profile or MockProfile
    frontend_context: Optional[dict] = None

    @property
    def is_admin(self) -> bool:
        return str(getattr(self.user, "role", "")).lower() in ("admin", "super_admin")

    @property
    def user_id(self) -> str:
        return str(getattr(self.user, "id", ""))

    @property
    def role(self) -> str:
        return str(getattr(self.user, "role", "user")).lower()

    @property
    def full_name(self) -> str:
        return str(getattr(self.user, "full_name", "Unknown User"))

    @property
    def warehouse_id(self) -> Optional[str]:
        wid = getattr(self.user, "warehouse_id", None)
        return str(wid) if wid else None


