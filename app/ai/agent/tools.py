"""PredictiX Chatbot – Pure-Python Tool Handlers & Zero-Token Handlers.

Architecture:
  - Zero-Token handlers: Greeting, Navigation, WhoAmI, FAQ
    → No LLM call at all. Instant, deterministic responses.
  - Database handler: executes SQL generated by a sub-agent
  - Knowledge handler: semantic search on the knowledge base
  - Prediction handler: queries all ML prediction tables
"""
