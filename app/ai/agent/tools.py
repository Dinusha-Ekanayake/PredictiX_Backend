def handle_faq(question: str, ctx: ToolContext) -> dict:
    """Fetch FAQs from Supabase, synthesize with LLM, and fallback to admin if not found."""
    from app.ai.services.llm_service import call_groq

    def _get_faq_fallback() -> dict:
        return {
            "answer": "Please reach out to our admins at **neuromindspredictix@gmail.com** and they'll get back to you as soon as possible.",
            "action_buttons": [{"label": "Copy Admin Email", "path": "copy:neuromindspredictix@gmail.com"}],
        }

    try:
        resp = (
            supabase.from_("faqs")
            .select("id,question,answer,category")
            .eq("is_active", True)
            .execute()
        )
        all_faqs = resp.data or []
    except Exception as e:
        log.warning("FAQ fetch failed: %s", e)
        all_faqs = []

    q_lower = question.lower()
    words = [w for w in q_lower.split() if len(w) > 2]
    scored = []
    for faq in all_faqs:
        faq_q = faq.get("question", "").lower()
        faq_a = faq.get("answer", "").lower()
        score = sum(2 for w in words if w in faq_q) + sum(1 for w in words if w in faq_a)
        if score > 0:
            scored.append((score, faq))

    scored.sort(key=lambda x: x[0], reverse=True)
    top = [faq for _, faq in scored[:4]]

    if not top:
        return _get_faq_fallback()

    context_str = "\n".join(
        f"Q: {faq['question']}\nA: {faq['answer']}" for faq in top
    )
    user_name = ctx.full_name.split()[0] if ctx.full_name else "there"

    try:
        summary, fb = call_groq(
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are PredictiX Assistant. Answer the user's question using ONLY the provided FAQ context. "
                        "CRITICAL INSTRUCTION: If the provided context does NOT contain the exact answer to the user's specific question (for example, they ask how to delete a ticket, but the context only explains how to open or view tickets), you MUST reply EXACTLY with the word: NOT_FOUND. Do not try to guess or invent an answer based on unrelated context. "
                        "If the context DOES answer the question accurately, be conversational, encouraging, and use simple language. "
                        "Never mention 'the FAQ', 'the context', or 'the database'. Just answer naturally. "
                        "Always start your response with a ✅ emoji and end with: '*Let me know if you need any more help! 😊*'"
                    ),
                },
                {
                    "role": "user",
                    "content": (
                        f"My name is {user_name}. My question is: \"{question}\"\n\n"
                        f"FAQ Context:\n{context_str}"
                    ),
                },
            ],
            model="llama-3.1-8b-instant",
            max_tokens=400,
            temperature=0.1,
        )
        
        if not summary or "NOT_FOUND" in str(summary).strip():
            return _get_faq_fallback()
            
        answer = fb + str(summary)
    except Exception as e:
        log.error("FAQ LLM synthesis failed: %s", e)
        return _get_faq_fallback()

    return {
        "answer": answer,
        "action_buttons": [],
    }


def handle_knowledge(question: str, ctx: ToolContext) -> dict:
    """Semantic search on knowledge base, then summarize with fast model."""
    from app.ai.services.llm_service import call_groq
    from app.ai.services.knowledge_service import search_knowledge

    results = search_knowledge(question, match_count=4)
    if not results:
        return {
            "answer": "📚 I couldn't find anything relevant in the knowledge base for that question. Try rephrasing or ask about a specific asset/ticket.",
            "action_buttons": [],
        }

    context_parts = [f"- {r.get('title', 'Article')}: {r.get('content', '')[:300]}" for r in results]
    context_str = "\n".join(context_parts)

    fallback_msg = ""
    try:
        summary, fallback_msg = call_groq(
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are PredictiX Assistant. Summarize the following knowledge base articles to answer the user's question. "
                        "Do NOT include general fleet statistics, counts of critical assets, or predicted failures (e.g. '205 assets at critical risk', '125 predicted to fail') unless the user's question explicitly asks for numbers, counts, or statistics. "
                        "Be concise (3-5 sentences). Use professional language. End with 'Is there anything else I can help with?'"
                    ),
                },
                {"role": "user", "content": f"Question: {question}\n\nKnowledge Base:\n{context_str}"},
            ],
            model="llama-3.1-8b-instant",
            max_tokens=300,
            temperature=0.4,
        )
    except Exception as e:
        log.error("Knowledge summarization failed: %s", e)
        summary = context_str

    return {
        "answer": fallback_msg + f"📚 {summary}",
        "action_buttons": [],
    }


def handle_database(question: str, ctx: ToolContext) -> dict:
    """Two-agent pipeline: Table Selector → SQL Generator → Execute → Summarize."""
    from app.ai.services.llm_service import call_groq

    def _get_generic_fallback() -> dict:
        # Instead of just throwing an email, let the LLM try to answer it based on general persona
        try:
            ans, fb = call_groq(
                messages=[
                    {
                        "role": "system",
                        "content": "You are Sidekick, the PredictiX AI Assistant. The user asked a question that couldn't be answered via database search. "
                                   "Answer it based on general knowledge of the PredictiX Smart Asset Management System. "
                                   "Do NOT include general fleet statistics, counts of critical assets, or predicted failures (e.g. '205 assets at critical risk', '125 predicted to fail') unless the user's question explicitly asks for numbers, counts, or statistics. "
                                   "Roles: Admins manage users, assets, and settings. Users can view assigned assets, create tickets, and run predictions. "
                                   "Keep it concise, friendly, and helpful. If you truly cannot answer it, tell them to contact neuromindspredictix@gmail.com."
                    },
                    {"role": "user", "content": question}
                ],
                model="llama-3.1-8b-instant",
                max_tokens=300,
                temperature=0.3,
            )
            if ans:
                return {"answer": fb + str(ans), "action_buttons": []}
        except Exception:
            pass
            
        return {
            "answer": "Please reach out to our admins at **neuromindspredictix@gmail.com** and they'll get back to you as soon as possible.",
            "action_buttons": [{"label": "Copy Admin Email", "path": "copy:neuromindspredictix@gmail.com"}],
        }

    def _get_contextual_fallback(error_reason: str) -> dict:
        fc = getattr(ctx, "frontend_context", None)
        if fc:
            try:
                ans, fb = call_groq(
                    messages=[
                        {
                            "role": "system",
                            "content": (
                                "You are Sidekick, the PredictiX AI Assistant. "
                                "We had trouble querying the database directly, but we have this cached frontend dashboard state: "
                                f"{str(fc)}\n\n"
                                "Answer the user's question as best as you can using only this cached data. Keep it friendly, helpful, and concise. "
                                "Do NOT mention 'frontend context', 'cached data', 'database errors', or 'SQL'. Just answer the question naturally. "
                                "Do NOT include general fleet statistics, counts of critical assets, or predicted failures from the cached state (e.g. '205 assets at critical risk', '125 predicted to fail') unless the user's question explicitly asks for numbers, counts, or statistics. "
                                "If you cannot answer the question using the provided state, say: 'The database is temporarily busy, but you can find this information on the main dashboard page.'"
                            )
                        },
                        {"role": "user", "content": question}
                    ],
                    model="llama-3.1-8b-instant",
                    max_tokens=300,
                    temperature=0.3,
                )
                if ans:
                    return {"answer": fb + str(ans), "action_buttons": []}
            except Exception as e:
                log.error("Failed to generate contextual fallback: %s", e)

        return {
            "answer": "⚠️ The database is temporarily busy. You can find this information on the dashboard or relevant asset/ticket pages using the navigation buttons below.",
            "action_buttons": [
                {"label": "Go to Dashboard", "path": "/admin/dashboard"},
                {"label": "View Assets", "path": "/admin/assets"},
            ],
        }

    # Collect fallback messages from models
    fallback_msg = ""

    # ── Step 0: Dashboard/Overview Fast-Path (100% UI Parity) ─────────────────
    q_lower = question.lower()
    
    # Check if this is a general stats summary request (e.g. details about X)
    general_summary_keywords = ["summary", "overview", "stats", "dashboard stats", "all stats"]
    is_general_summary = any(w in q_lower for w in general_summary_keywords)
    is_details_summary = any(
        f"details about {x}" in q_lower or 
        f"details of {x}" in q_lower or 
        f"{x} details" in q_lower or 
        f"overview of {x}" in q_lower or 
        f"{x} overview" in q_lower or 
        f"{x} stats" in q_lower 
        for x in ["asset", "ticket", "user", "warehouse"]
    )
    is_summary = (is_general_summary or is_details_summary) and not any(w in q_lower for w in ["list", "show all", "get all", "find all"])

    if is_summary:
        if ctx.role not in ["admin", "super_admin"]:
            return {
                "answer": "🔒 You do not have permission to view system-wide statistics. You can only view and manage your own tickets and assigned assets.",
                "action_buttons": [],
            }
        try:
            from app.models import Asset, Ticket, Profile, PdmBatchPrediction
            from sqlalchemy import func, cast, String, case
            
            is_asset = "asset" in q_lower
            is_ticket = "ticket" in q_lower
            is_user = "user" in q_lower or "profile" in q_lower
            
            # 1. Fetch Asset Stats if requested or for overall view
            total_assets, operational, maintenance, critical_band, offline, avg_health_val = 0, 0, 0, 0, 0, 0
            if is_asset or not (is_ticket or is_user):
                asset_q = ctx.db.query(Asset)
                if ctx.warehouse_id:
                    asset_q = asset_q.filter(Asset.warehouse_id == ctx.warehouse_id)
                asset_rows = asset_q.with_entities(
                    func.count(Asset.id),
                    func.count(Asset.id).filter(cast(Asset.status, String) == "active"),
                    func.count(Asset.id).filter(cast(Asset.status, String) == "under_maintenance"),
                    func.count(Asset.id).filter(Asset.health_band == "critical"),
                    func.count(Asset.id).filter(cast(Asset.status, String).in_(("inactive", "decommissioned"))),
                ).one()
                total_assets, operational, maintenance, critical_band, offline = asset_rows
                total_assets = int(total_assets or 0)
                operational = int(operational or 0)
                maintenance = int(maintenance or 0)
                critical_band = int(critical_band or 0)
                offline = int(offline or 0)

                health_q = (
                    ctx.db.query(func.avg(PdmBatchPrediction.health_score))
                    .select_from(Asset)
                    .join(
                        PdmBatchPrediction,
                        (PdmBatchPrediction.asset_id == Asset.id) & (PdmBatchPrediction.status == "ok"),
                    )
                )
                if ctx.warehouse_id:
                    health_q = health_q.filter(Asset.warehouse_id == ctx.warehouse_id)
                avg_health = health_q.scalar()
                avg_health_val = int(round(float(avg_health))) if avg_health is not None else 64

            # 2. Fetch Ticket Stats if requested or for overall view
            open_tickets, high_priority, tickets_resolved, avg_resolution_days = 0, 0, 0, 0.0
            if is_ticket or not (is_asset or is_user):
                ticket_q = ctx.db.query(Ticket)
                if ctx.warehouse_id:
                    ticket_q = ticket_q.filter(Ticket.warehouse_id == ctx.warehouse_id)
                
                ticket_rows = ticket_q.with_entities(
                    func.count(Ticket.id).filter(Ticket.status.notin_(('closed', 'cancelled'))),
                    func.count(Ticket.id).filter((Ticket.priority == 'high') & Ticket.status.notin_(('closed', 'cancelled'))),
                    func.count(Ticket.id).filter(Ticket.status.in_(('resolved', 'closed'))),
                    func.avg(
                        case(
                            [(func.coalesce(Ticket.closed_at, Ticket.resolved_at).isnot(None) & Ticket.created_at.isnot(None),
                             func.extract('epoch', func.coalesce(Ticket.closed_at, Ticket.resolved_at) - Ticket.created_at) / 86400.0)],
                            else_=None
                        )
                    )
                ).one()
                
                open_tickets, high_priority, tickets_resolved, avg_res = ticket_rows
                open_tickets = int(open_tickets or 0)
                high_priority = int(high_priority or 0)
                tickets_resolved = int(tickets_resolved or 0)
                avg_resolution_days = round(float(avg_res), 1) if avg_res is not None else 0.0

            # 3. Fetch User Stats if requested or for overall view
            total_users, active_users, admins, regular_users = 0, 0, 0, 0
            if is_user or not (is_asset or is_ticket):
                users_q = ctx.db.query(Profile)
                if ctx.warehouse_id:
                    users_q = users_q.filter((Profile.warehouse_id == ctx.warehouse_id) | (Profile.warehouse_id.is_(None)))
                all_users = users_q.all()
                total_users = len(all_users)
                active_users = sum(1 for u in all_users if getattr(u, "status", "").lower() == "active")
                admins = sum(1 for u in all_users if getattr(u, "role", "").lower() == "admin")
                regular_users = sum(1 for u in all_users if getattr(u, "role", "").lower() == "user")

            # 4. Construct beautiful Markdown response
            if is_asset:
                answer = (
                    f"⚙️ **Asset Fleet Overview**\n\n"
                    f"Here is a summary of the assets in this warehouse:\n\n"
                    f"• **Total Assets:** {total_assets:,}\n"
                    f"• **Average Health:** {avg_health_val}%\n"
                    f"• **Operational (Active):** {operational:,}\n"
                    f"• **Under Maintenance:** {maintenance:,}\n"
                    f"• **Critical Band:** {critical_band:,}\n"
                    f"• **Offline / Inactive:** {offline:,}"
                )
                action_buttons = [{"label": "View Assets Dashboard", "path": "/admin/assets"}]
            elif is_ticket:
                answer = (
                    f"🎫 **Tickets & Helpdesk Overview**\n\n"
                    f"Here is a summary of the support tickets in this warehouse:\n\n"
                    f"• **Open Tickets:** {open_tickets:,}\n"
                    f"• **High Priority:** {high_priority:,}\n"
                    f"• **Tickets Resolved:** {tickets_resolved:,}\n"
                    f"• **Average Resolution:** {avg_resolution_days} days"
                )
                action_buttons = [{"label": "View Tickets Helpdesk", "path": "/admin/tickets"}]
            elif is_user:
                answer = (
                    f"👥 **User & Team Overview**\n\n"
                    f"Here is a summary of team accounts in this warehouse:\n\n"
                    f"• **Total Users:** {total_users:,}\n"
                    f"• **Active Users:** {active_users:,}\n"
                    f"• **Administrators:** {admins:,}\n"
                    f"• **Standard Users:** {regular_users:,}"
                )
                action_buttons = [{"label": "View User Management", "path": "/admin/users"}]
            else:
                # Overall system-wide overview
                answer = (
                    f"📊 **System-Wide Dashboard Summary**\n\n"
                    f"Here is a summary of current system operations:\n\n"
                    f"• **Total Assets:** {total_assets:,} ({avg_health_val}% Avg. Health)\n"
                    f"• **Active Tickets:** {open_tickets:,} ({high_priority:,} High Priority)\n"
                    f"• **Active Team Members:** {active_users:,} of {total_users:,} total users"
                )
                action_buttons = [{"label": "Go to Dashboard", "path": "/admin/dashboard"}]

            return {
                "answer": answer,
                "action_buttons": action_buttons
            }
        except Exception as e:
            log.error("Overview fast-path failed: %s", e)
            return _get_generic_fallback()
    else:
        goto_summarizer = False

    if not goto_summarizer:
        # ── Step 1: Table Selector (fast model) ──────────────────────────────────
        table_list = ", ".join(DB_SCHEMAS.keys())
        selector_prompt = (
            f"You are a database table selector for PredictiX (Smart Asset Management System).\n"
            f"The user asked: \"{question}\"\n\n"
            f"Available tables: {table_list}\n\n"
            "Respond with ONLY a comma-separated list of up to 4 table names that are needed to answer this question. "
            "No explanations, no other text."
        )
        try:
            raw_tables, fb = call_groq(
                messages=[{"role": "user", "content": selector_prompt}],
                model="llama-3.1-8b-instant",
                max_tokens=60,
                temperature=0.1,
            )
            if fb and not fallback_msg: fallback_msg = fb
            selected_tables = [t.strip() for t in str(raw_tables).split(",") if t.strip() in DB_SCHEMAS]
        except Exception as e:
            log.error("Table selector failed: %s", e)
            selected_tables = ["tickets", "assets"]

        if not selected_tables:
            selected_tables = ["tickets", "assets"]

        # ── Step 2: SQL Generator (heavy model) ──────────────────────────────────
        schema_str = "\n".join(
            f"Table '{t}': columns → {DB_SCHEMAS[t]}" for t in selected_tables
        )

        # Build role-based scoping instruction
        if ctx.is_admin:
            role_instructions = "SECURITY RULE: The user is an ADMIN. You may query ALL records across the entire system."
            if ctx.warehouse_id:
                role_instructions += f" The admin is scoped to warehouse_id = '{ctx.warehouse_id}'."
        else:
            role_instructions = (
                f"SECURITY RULE: The current user is a STANDARD USER (id='{ctx.user_id}'). "
                "You MUST add a WHERE clause to only show records where created_by = '{user_id}' OR assigned_to = '{user_id}'. "
                "Never expose other users' private data."
            ).replace("{user_id}", ctx.user_id)

        sql_prompt = (
            f"You are a PostgreSQL expert. Write a query to answer: \"{question}\"\n"
            f"Use ONLY these tables: {selected_tables}\n"
            f"Schema:\n{schema_str}\n"
            f"{role_instructions}\n"
            "CRITICAL INSTRUCTIONS:\n"
            "1. If the user asks for 'details', 'info', or queries a specific record (like a specific Ticket ID, Asset Name, or User), you MUST use `SELECT *` so the ID and all fields are returned. DO NOT use `COUNT(*)` or aggregate functions for specific record lookups.\n"
            "2. Respond ONLY with raw valid PostgreSQL SQL. No markdown formatting, no backticks, no explanations.\n"
            "3. If the question cannot be answered using the schema, or violates the security rule, output EXACTLY: 'ERROR: reason'"
        )

        try:
            raw_sql, fb = call_groq(
                messages=[{"role": "user", "content": sql_prompt}],
                model="llama-3.3-70b-versatile",
                max_tokens=350,
                temperature=0.1,
            )
            if fb and not fallback_msg: fallback_msg = fb
            sql = str(raw_sql).strip().lstrip("```sql").lstrip("```").rstrip("```").strip()
        except Exception as e:
            log.error("SQL generator failed: %s", e)
            return _get_contextual_fallback("SQL generator failed")

        if sql.startswith("ERROR: Permission Denied"):
            return {
                "answer": "🔒 You do not have permission to view system-wide data. You can only view records assigned to or created by you.",
                "action_buttons": [],
            }

        if sql.startswith("ERROR: Permission Denied"):
            return {
                "answer": "🔒 You do not have permission to view system-wide data. You can only view records assigned to or created by you.",
                "action_buttons": [],
            }

        if sql.startswith("ERROR:"):
            return _get_contextual_fallback(sql)

        # Security guard: block any mutation
        import re
        sql_upper = sql.upper()
        for dangerous in ["INSERT", "UPDATE", "DELETE", "DROP", "ALTER", "CREATE", "TRUNCATE", "GRANT"]:
            if re.search(rf"\b{dangerous}\b", sql_upper):
                return _get_generic_fallback()

        # ── Step 3: Execute (with self-healing retry on DB error) ────────────────
        if ctx.db is None:
            return {"answer": "⚠️ Database is not available right now. Please try again in a moment.", "action_buttons": []}

        def _run_sql(sql_to_run: str):
            result = ctx.db.execute(text(sql_to_run)).fetchall()
            if not result:
                return None
            keys = list(result[0]._mapping.keys())
            return [dict(zip(keys, row)) for row in result[:50]]

        rows = None
        try:
            rows = _run_sql(sql)
        except Exception as first_err:
            log.warning("SQL execution failed (attempt 1): %s | SQL: %s", first_err, sql)
            ctx.db.rollback()
            # Self-healing: feed the error back to the LLM to fix the SQL
            try:
                fix_prompt = (
                    f"The following PostgreSQL query failed with this error:\n"
                    f"ERROR: {str(first_err)[:300]}\n\n"
                    f"FAILED SQL:\n{sql}\n\n"
                    f"SCHEMA (correct ENUM values):\n{schema_str}\n\n"
                    "Fix the SQL query. Common fixes:\n"
                    "- assets.status valid values: active, inactive, maintenance, retired, disposed (NOT 'open')\n"
                    "- tickets.status valid values: open, in_progress, pending, resolved, closed, cancelled\n"
                    "- Use CAST if comparing text with enum column\n"
                    "Output ONLY the corrected raw SQL. No markdown, no backticks."
                )
                corrected_sql_raw, _ = call_groq(
                    messages=[{"role": "user", "content": fix_prompt}],
                    model="llama-3.3-70b-versatile",
                    max_tokens=350,
                    temperature=0.1,
                )
                corrected_sql = str(corrected_sql_raw).strip().lstrip("```sql").lstrip("```").rstrip("```").strip()
                log.info("Self-healed SQL: %s", corrected_sql)
                rows = _run_sql(corrected_sql)
                sql = corrected_sql  # update for logging
            except Exception as second_err:
                log.error("SQL self-healing also failed: %s", second_err)
                ctx.db.rollback()
                return _get_contextual_fallback(str(second_err))

        if rows is None:
            return {"answer": "📊 The query ran successfully but returned no results. The data matching your request may not exist yet.", "action_buttons": []}

    # ── Fast-Path for Single Records (Widget) ──────────────────────────────
    # If the database returns exactly 1 record AND it has an ID, we bypass the
    # text summarizer and return a rich widget.
    if rows and len(rows) == 1 and "id" in rows[0] and not goto_summarizer:
        row = rows[0]
        row_id = str(row["id"])
        
        # Determine table/type
        table_type = "unknown"
        if "tickets" in selected_tables: table_type = "ticket"
        elif "assets" in selected_tables: table_type = "asset"
        elif "profiles" in selected_tables or "users" in selected_tables: table_type = "user"
        
        if table_type != "unknown":
            action_buttons = []
            if table_type == "ticket":
                base_path = "/admin/tickets" if ctx.is_admin else "/user/tickets"
                action_buttons.append({"label": "View Ticket", "path": f"{base_path}?ticket_id={row_id}"})
            elif table_type == "asset":
                action_buttons.append({"label": "View Asset", "path": f"/admin/assets?asset_id={row_id}"})
            elif table_type == "user":
                action_buttons.append({"label": "View User", "path": f"/admin/users?user_id={row_id}"})
                
            # Convert row to dict, ensuring datetime objects are strings
            def _serialize(v):
                if hasattr(v, "isoformat"): return v.isoformat()
                return str(v) if v is not None else None
            
            clean_data = {str(k): _serialize(v) for k, v in row.items()}
            
            return {
                "answer": f"Here is the detailed summary card you requested:",
                "action_buttons": action_buttons,
                "widget_type": "RECORD_SUMMARY",
                "widget_data": {
                    "type": table_type,
                    "data": clean_data
                }
            }

    # ── Step 4: Summarize (fast model) ───────────────────────────────────────
    row_str = str(rows[:30])  # cap context to keep tokens low

    # Build a direct plain-text fallback from the raw rows (used if LLM fails)
    def _build_fallback(rows: list[dict]) -> str:
        if not rows:
            return "📊 No data found."
        lines = [f"📊 **Results ({len(rows)} record{'s' if len(rows) != 1 else ''}):**\n"]
        for i, row in enumerate(rows):
            keys = list(row.keys())
            # Clean format for two-column stats (e.g. Metric/Count, Category/Total)
            if len(keys) == 2 and str(keys[1]).lower() in ["count", "value", "total", "amount", "sum"]:
                lines.append(f"• **{row[keys[0]]}:** {row[keys[1]]}")
            else:
                lines.append(f"\n### 📝 Record #{i+1}")
                for k, v in row.items():
                    if v is not None and str(v).strip():
                        # Exclude displaying raw system IDs in the fallback list to keep it clean
                        if k == "id" or k.endswith("_id"):
                            continue
                        pretty_key = str(k).replace("_", " ").title()
                        lines.append(f"  - **{pretty_key}:** {v}")
        return "\n".join(lines)

    summarizer_prompt = (
        f"You are PredictiX Assistant. A user asked: \"{question}\"\n"
        f"The database returned this data: {row_str}\n\n"
        "INSTRUCTIONS — follow these EXACTLY:\n"
        "1. If the user asks for details of a SPECIFIC record (like a specific ticket, asset, or user) and there is only 1 record returned, output its details clearly in a bulleted list (e.g. Title, Status, Description, Priority). Do NOT just output aggregate counts.\n"
        "2. If the user asks for general stats, start with a ONE-LINE summary of the TOTAL count, then list the breakdown of categories with their exact count (e.g. 🎫 **Open Tickets:** 5 items).\n"
        "3. Use 👥 for users, 🎫 for tickets, ⚙️ for assets, 📊 for general stats.\n"
        "4. Quote EXACT numbers and data — never round or approximate.\n"
        "5. Never expose raw UUIDs unless the user explicitly provided one in their question.\n"
        "6. End with a polite, helpful closing sentence."
    )
    try:
        summary, fb = call_groq(
            messages=[{"role": "user", "content": summarizer_prompt}],
            model="llama-3.1-8b-instant",
            max_tokens=400,
            temperature=0.2,
        )
        if fb and not fallback_msg: fallback_msg = fb
        if not summary or len(str(summary).strip()) < 10:
            summary = _build_fallback(rows)
    except Exception as e:
        log.error("Summarizer failed: %s", e)
        summary = _build_fallback(rows)

    # Determine interactive action buttons based on queried tables
    action_buttons = []
    
    # Fast-path for single records: provide a deep-link button directly to the item!
    if rows and len(rows) == 1 and "id" in rows[0]:
        row_id = str(rows[0]["id"])
        if "tickets" in selected_tables:
            base_path = "/admin/tickets" if ctx.is_admin else "/user/tickets"
            action_buttons.append({"label": "View Ticket", "path": f"{base_path}?ticket_id={row_id}"})
        elif "assets" in selected_tables:
            action_buttons.append({"label": "View Asset", "path": f"/admin/assets?asset_id={row_id}"})
        elif "profiles" in selected_tables or "users" in selected_tables:
            action_buttons.append({"label": "View User", "path": f"/admin/users?user_id={row_id}"})
    else:
        if "profiles" in selected_tables or "users" in selected_tables:
            action_buttons.append({"label": "Manage Users", "path": "/admin/users"})
        if "tickets" in selected_tables:
            base_path = "/admin/tickets" if ctx.is_admin else "/user/tickets"
            action_buttons.append({"label": "View Tickets", "path": base_path})
        if "assets" in selected_tables:
            action_buttons.append({"label": "View Assets", "path": "/admin/assets"})
        if "warehouses" in selected_tables:
            action_buttons.append({"label": "View Warehouses", "path": "/admin/warehouse"})

    # Limit to 2 buttons max so it doesn't clutter the UI
    action_buttons = action_buttons[:2]

    return {
        "answer": fallback_msg + str(summary),
        "action_buttons": action_buttons,
    }



