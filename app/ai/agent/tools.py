def handle_whoami(ctx: ToolContext) -> dict:
    """Returns user profile without any LLM call."""
    user = ctx.user
    role = getattr(user, "role", "user")
    full_name = getattr(user, "full_name", "Unknown")
    email = getattr(user, "email", "N/A")
    employee_id = getattr(user, "employee_id", "N/A")
    status = getattr(user, "status", "active")
    wid = getattr(user, "warehouse_id", None)
    did = getattr(user, "department_id", None)

    lines = [
        f"👤 **Your Profile**\n",
        f"• **Name:** {full_name}",
        f"• **Email:** {email}",
        f"• **Role:** {role.replace('_', ' ').title()}",
        f"• **Employee ID:** {employee_id}",
        f"• **Status:** {'✅ Active' if status == 'active' else '❌ ' + status.title()}",
    ]
    if wid:
        lines.append(f"• **Warehouse ID:** {wid}")
    if did:
        lines.append(f"• **Department ID:** {did}")

    return {
        "answer": "\n".join(lines),
        "action_buttons": [{"label": "Go to My Profile", "path": "/user/profile"}],
    }


