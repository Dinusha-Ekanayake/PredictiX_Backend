"""Generate the reference list from the registry and the ingest state.

Two outputs, both rebuilt on every run so they can never drift from the
registry: kb/REFERENCES.md (IEEE-style list with licence and provenance) and
kb/references.bib (BibTeX for reports and the viva).
"""
from __future__ import annotations

from typing import Optional

from app.kb.pipeline.registry import Registry, Source

_JURISDICTION = {"US": "United States", "UK": "United Kingdom", "LK": "Sri Lanka", "INT": "International"}


def _year(source: Source) -> str:
    return "n.d." if source.published == "n.d." else source.published[:4]


def ieee(source: Source, accessed: Optional[str]) -> str:
    who = ", ".join(source.authors) if source.authors else source.publisher
    parts = [f"{who}, “{source.title},”"]
    if source.container:
        parts.append(f"in *{source.container}*,")
    if source.edition:
        parts.append(f"{source.edition},")
    if source.identifiers:
        parts.append(f"{'; '.join(source.identifiers)},")
    if source.authors:
        parts.append(f"{source.publisher},")
    parts.append(f"{_year(source)}.")
    if source.doi:
        parts.append(f"doi: {source.doi}.")
    parts.append(f"[Online]. Available: {source.url}")
    if accessed:
        parts.append(f"(accessed {accessed}).")
    return " ".join(parts)


def render_markdown(registry: Registry, state: dict[str, dict]) -> str:
    lines = [
        "# Knowledge base references",
        "",
        "Generated by `python -m app.kb.pipeline references` from `kb/sources.yaml` and the",
        "ingest state in the database. Do not edit by hand.",
        "",
        "Each source is cited in answers by its ID. The checksum identifies the exact",
        "original file archived in the private `kb-sources` bucket.",
        "",
        "## Sources",
        "",
    ]
    for source in registry.sources:
        st = state.get(source.id, {})
        accessed = st["retrieved_at"].date().isoformat() if st.get("retrieved_at") else None
        lines.append(f"**[{source.id}]** {ieee(source, accessed)}")
        lines.append("")
        scope = "All warehouses" if source.scope == "network" else ", ".join(source.warehouses)
        lines += [
            f"- Licence: {source.licence}" + (f" ({source.licence_url})" if source.licence_url else ""),
            f"- Attribution: {source.attribution}",
            f"- Jurisdiction: {_JURISDICTION[source.jurisdiction]}. {source.applicability}",
            f"- Scope: {scope}. Audience: {', '.join(source.audience)}. Used by: {', '.join(source.supports)}.",
            f"- Status: {st.get('status', 'not yet ingested')}"
            + (f", version {st['version']}, {st['chunk_count']} passages" if st.get("version") else "")
            + (f", sha256 `{st['sha256'][:16]}...`" if st.get("sha256") else "")
            + f". Review due {source.review_due.isoformat()}.",
            "",
        ]
    if registry.excluded:
        lines += ["## Considered and excluded", "", "| ID | Title | Reason | Decided |", "|---|---|---|---|"]
        for x in registry.excluded:
            lines.append(f"| {x.id} | [{x.title}]({x.url}) | {x.reason} | {x.decided.isoformat()} |")
        lines.append("")
    return "\n".join(lines)


def _bib_escape(value: str) -> str:
    return value.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def render_bibtex(registry: Registry, state: dict[str, dict]) -> str:
    entries = []
    for s in registry.sources:
        kind = "article" if s.doc_type == "review_article" else "misc"
        fields = {
            "title": s.title,
            "author": " and ".join(s.authors) if s.authors else "{" + s.publisher + "}",
            "year": _year(s),
            "publisher": s.publisher,
            "howpublished": f"\\url{{{s.url}}}",
            "note": f"{s.licence}. Knowledge base source {s.id}.",
        }
        if s.container:
            fields["journal" if kind == "article" else "series"] = s.container
        if s.doi:
            fields["doi"] = s.doi
        if s.identifiers:
            fields["number"] = "; ".join(s.identifiers)
        st = state.get(s.id, {})
        if st.get("retrieved_at"):
            fields["urldate"] = st["retrieved_at"].date().isoformat()
        body = ",\n".join(
            f"  {k} = {{{_bib_escape(v) if k not in ('howpublished', 'author') else v}}}"
            for k, v in fields.items()
        )
        entries.append(f"@{kind}{{predictix_{s.id.lower().replace('-', '_')},\n{body}\n}}")
    return "\n\n".join(entries) + "\n"
